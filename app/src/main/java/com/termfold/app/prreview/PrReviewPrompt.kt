package com.termfold.app.prreview

object PrReviewPrompt {
    fun prefix(session: PrReviewSession): String = buildString {
        appendLine("You are reviewing GitHub pull request #${session.number} in ${session.owner}/${session.repo}.")
        appendLine("URL: ${session.url}")
        appendLine("Head branch (already checked out in this workspace): ${session.headBranch}")
        appendLine()
        appendLine("Facts pack (in-diff boundary). Read these files; do not guess the diff:")
        appendLine("- ${PrReviewFactsPack.DIR_NAME}/${PrReviewFactsPack.DIFF_FILE}")
        appendLine("- ${PrReviewFactsPack.DIR_NAME}/${PrReviewFactsPack.FILES_FILE}")
        appendLine("- ${PrReviewFactsPack.DIR_NAME}/${PrReviewFactsPack.PR_FILE}")
        appendLine("- ${PrReviewFactsPack.DIR_NAME}/${PrReviewFactsPack.COMMENTS_FILE}")
        appendLine("In-diff findings MUST cite lines that appear in pr.diff. Other issues go in findings with inDiff=false.")
        appendLine()
        appendLine("Do not use the browser or look up docs on the web unless the user explicitly asks to verify online.")
        appendLine()
        appendLine("Emit exactly one fenced JSON block with language tag ${PrReviewReportParser.FENCE} using schemaVersion 1:")
        appendLine("{")
        appendLine("  \"schemaVersion\": 1,")
        appendLine("  \"summary\": \"what this PR does\",")
        appendLine("  \"risk\": \"low|medium|high\",")
        appendLine("  \"findings\": [{")
        appendLine("    \"id\": \"A-1\",")
        appendLine("    \"surface\": \"android|linux-guest|shared|ci-docs|ios\",")
        appendLine("    \"severity\": \"blocker|should-fix|nit|question\",")
        appendLine("    \"title\": \"...\", \"location\": \"file:line\",")
        appendLine("    \"inDiff\": true, \"evidence\": \"...\", \"suggestion\": \"...\"")
        appendLine("  }],")
        appendLine("  \"coverage\": { \"reviewed\": [\"paths\"], \"skipped\": [\"paths\"] },")
        appendLine("  \"missingTests\": [], \"openQuestions\": []")
        appendLine("}")
        appendLine("Write for a busy human, not a compiler. Use short, everyday words.")
        appendLine("summary: one or two plain sentences — what changed, and what could break.")
        appendLine("title: a simple headline (no jargon unless you immediately explain it).")
        appendLine("evidence: \"What's wrong\" in plain language, then the file clue.")
        appendLine("suggestion: \"How to fix\" in one short sentence.")
        appendLine("missingTests and openQuestions: same — short and concrete.")
        appendLine("Each finding has exactly one surface. Use ios only if files.txt includes iOS paths; otherwise omit ios findings.")
        appendLine("After the JSON, ask which finding ids to fix (all, a subset, or none), in plain words.")
        appendLine("Do not apply code changes until the user chooses ids. Do not push.")
        appendLine("Never modify the golden project tree; this workspace is the isolated PR copy.")
    }
}
